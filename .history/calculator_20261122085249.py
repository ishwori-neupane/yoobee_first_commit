num1=float(input("Enter first number"))
num2=float(input("Enter Second number"))
operator=input("Enter you operator (-,+,*,/)")

if operator =="-":
    sub=num1-num2
    print(sub)

elif operator=="+":
    add=num1+num2
    print(add)
elif operator=="*":
    mul=num1*num2
    print(mul)
else :
    div=num1/num2
    print(div)
   

    


